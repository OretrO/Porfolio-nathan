export const getTranslation = (language, key) => {
  const keys = key.split('.')
  let value = translations[language]

  for (const k of keys) {
    if (value && typeof value === 'object') {
      value = value[k]
    } else {
      return key // retourne la clé si la traduction n'existe pas
    }
  }

  return value || key
}

